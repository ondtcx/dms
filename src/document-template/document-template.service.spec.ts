import { DocumentTemplateService } from './document-template.service';
import { UserRole } from '../auth/role.enum';
import { DirectoryService } from '../directory/directory.service';
import * as fs from 'fs';
import * as path from 'path';

jest.mock('fs', () => ({
  ...jest.requireActual('fs'),
  existsSync: jest.fn((file: string) => !file.endsWith('.pdf') && !file.endsWith('.html')),
  promises: { ...jest.requireActual('fs').promises, unlink: jest.fn().mockResolvedValue(undefined) },
  statSync: jest.fn(() => ({ size: 3 })),
}));

jest.mock('./document-generator.service', () => ({
  DocumentGeneratorService: class {},
}));

describe('DocumentTemplateService.updateDocumentFromTemplate', () => {
  afterEach(() => {
    jest.restoreAllMocks();
  });

  function receptionFixture() {
    const document = { id: 42, uploadedById: 'author', directoryId: 9, receptionOriginDirectoryId: 2,
      currentVersion: 1, isPublic: false, deletedAt: null, templateData: { templateId: 7 },
      versions: [{ id: 10, version: 1, filename: 'a.pdf', path: '/history/a.pdf' }] };
    const db: any = {
      $queryRaw: jest.fn(),
      document: { findUnique: jest.fn().mockResolvedValue(document), update: jest.fn().mockResolvedValue({ id: 42, currentVersion: 2 }) },
      documentVersion: { create: jest.fn().mockResolvedValue({ id: 11 }), update: jest.fn() },
      documentAccess: { create: jest.fn() },
      documentWorkflow: { findFirst: jest.fn().mockResolvedValue(null), update: jest.fn() },
      user: { findUnique: jest.fn().mockResolvedValue({ id: 'author', role: 'admin' }) },
      directory: { findUnique: jest.fn().mockResolvedValue({ id: 2, receptionEnabled: true, createdById: 'author' }) },
      directoryUserParticipant: { findUnique: jest.fn().mockResolvedValue({ peerRead: true }) },
      directoryRoleParticipant: { findMany: jest.fn().mockResolvedValue([]) },
      directoryDelegate: { findUnique: jest.fn().mockResolvedValue({ full: true }) },
      documentTemplate: { findUnique: jest.fn().mockResolvedValue({ id: 7, name: 'Acta', isActive: true,
        fields: { fields: [] }, outputFormat: 'pdf', htmlTemplate: '<p />', styles: '' }) },
    };
    db.$transaction = jest.fn(async cb => cb(db));
    const generator: any = { generatePDF: jest.fn().mockResolvedValue(Buffer.from('pdf')),
      saveDocumentToFile: jest.fn(async (_buffer, filename, dir) => path.join(dir, filename)) };
    const thumbnail: any = { regenerateThumbnail: jest.fn().mockResolvedValue(undefined) };
    const service = new DocumentTemplateService(db, generator, {} as any, thumbnail, {} as any, new DirectoryService(db));
    jest.spyOn(service as any, 'getInstitutionMetadata').mockResolvedValue({});
    (fs.promises.unlink as jest.Mock).mockClear();
    return { db, document, generator, thumbnail, service };
  }
  it('rechecks live membership after generating bytes and before saving any file', async () => {
    const { db, service, generator } = receptionFixture();
    generator.generatePDF.mockImplementation(async () => {
      db.directoryUserParticipant.findUnique.mockResolvedValue(null);
      return Buffer.from('pdf');
    });
    await expect(service.updateDocumentFromTemplate(42, { formData: {} }, 'author', UserRole.ADMIN)).rejects.toThrow('participación');
    expect(generator.saveDocumentToFile).not.toHaveBeenCalled();
    expect(fs.promises.unlink).not.toHaveBeenCalled();
    expect(db.documentVersion.update).not.toHaveBeenCalled();
    expect(db.document.update).not.toHaveBeenCalled();
    expect(db.$transaction).toHaveBeenCalledWith(expect.any(Function), { isolationLevel: 'Serializable', timeout: 30000 });
  });
  it('rejects a concurrently replaced base version before persisting generated bytes', async () => {
    const { db, document, service, generator } = receptionFixture();
    db.$queryRaw.mockImplementation(async () => {
      db.document.findUnique.mockResolvedValue({ ...document, currentVersion: 2, versions: [{ ...document.versions[0], id: 12 }] });
    });
    await expect(service.updateDocumentFromTemplate(42, { formData: {} }, 'author', UserRole.USER)).rejects.toThrow('cambió durante la generación');
    expect(generator.saveDocumentToFile).not.toHaveBeenCalled();
    expect(fs.promises.unlink).not.toHaveBeenCalled();
    expect(db.documentVersion.create).not.toHaveBeenCalled();
  });
  it('preserves correction evidence, supersession and unchanged-public persistence atomically', async () => {
    const { db, service } = receptionFixture();
    db.documentWorkflow.findFirst.mockResolvedValue({ id: 3, status: 'CHANGES_REQUESTED', initiatedById: 'author' });
    await service.updateDocumentFromTemplate(42, { formData: { title: 'Nuevo' }, isPublic: false }, 'author', UserRole.ADMIN);
    expect(db.documentVersion.update).toHaveBeenCalledWith({ where: { id: 10 }, data: { supersededAt: expect.any(Date) } });
    expect(db.documentVersion.create).toHaveBeenCalledWith({ data: expect.objectContaining({ version: 2, workflowId: 3, source: 'CAMBIOS_SOLICITADOS' }) });
    expect(db.documentWorkflow.update).toHaveBeenCalledWith({ where: { id: 3 }, data: { documentVersionId: 11 } });
    expect(db.document.update).toHaveBeenCalledWith(expect.objectContaining({ data: expect.objectContaining({ currentVersion: 2, isPublic: false }) }));
  });
  it('denies actual public changes and active review edits before generating bytes', async () => {
    const { db, service, generator } = receptionFixture();
    await expect(service.updateDocumentFromTemplate(42, { formData: {}, isPublic: true }, 'author', UserRole.ADMIN)).rejects.toThrow('gestionar');
    db.documentWorkflow.findFirst.mockResolvedValue({ id: 3, status: 'PENDING', initiatedById: 'author' });
    await expect(service.updateDocumentFromTemplate(42, { formData: {} }, 'author', UserRole.ADMIN)).rejects.toThrow('workflow activo');
    expect(generator.generatePDF).not.toHaveBeenCalled();
  });
  it('cleans only the candidate file when the transaction fails after saving it', async () => {
    const { db, service, generator, thumbnail } = receptionFixture();
    db.document.update.mockRejectedValue(new Error('write failed'));
    await expect(service.updateDocumentFromTemplate(42, { formData: {} }, 'author', UserRole.USER)).rejects.toThrow('write failed');
    const [, name, dir] = generator.saveDocumentToFile.mock.calls[0];
    expect(fs.promises.unlink).toHaveBeenCalledTimes(1);
    expect(fs.promises.unlink).toHaveBeenCalledWith(path.join(dir, name));
    expect(fs.promises.unlink).not.toHaveBeenCalledWith('/history/a.pdf');
    expect(thumbnail.regenerateThumbnail).not.toHaveBeenCalled();
  });
  it('never cleans committed files after thumbnail failure', async () => {
    const { service, thumbnail } = receptionFixture();
    thumbnail.regenerateThumbnail.mockRejectedValue(new Error('thumbnail failed'));
    await expect(service.updateDocumentFromTemplate(42, { formData: {} }, 'author', UserRole.USER)).resolves.toBeDefined();
    expect(fs.promises.unlink).not.toHaveBeenCalled();
  });

  it.each([['peer', true], ['author', false]])('denies reception template mutation for %s before generation', async (actor, participant) => {
    const db: any = {
      document: { findUnique: jest.fn().mockResolvedValue({ id: 42, uploadedById: 'author', directoryId: null, receptionOriginDirectoryId: 2, isPublic: false }) },
      user: { findUnique: jest.fn().mockResolvedValue({ id: actor, role: 'admin' }) },
      directory: { findUnique: jest.fn().mockResolvedValue({ id: 2, receptionEnabled: true, createdById: actor }) },
      directoryUserParticipant: { findUnique: jest.fn().mockResolvedValue(participant ? { peerRead: true } : null) },
      directoryRoleParticipant: { findMany: jest.fn().mockResolvedValue([]) },
      directoryDelegate: { findUnique: jest.fn().mockResolvedValue({ full: true }) },
      documentTemplate: { findUnique: jest.fn() },
    };
    const generator: any = { generatePDF: jest.fn(), saveDocumentToFile: jest.fn() };
    const service = new (DocumentTemplateService as any)(db, generator, {}, {}, {}, new DirectoryService(db));
    await expect(service.updateDocumentFromTemplate(42, { formData: {} }, actor, UserRole.ADMIN))
      .rejects.toThrow(actor === 'peer' ? 'autor' : 'participación');
    expect(db.documentTemplate.findUnique).not.toHaveBeenCalled();
    expect(generator.generatePDF).not.toHaveBeenCalled();
    expect(generator.saveDocumentToFile).not.toHaveBeenCalled();
  });

  it('denies non-owner rector visibility changes before template side effects', async () => {
    const prisma: any = {
      document: { findUnique: jest.fn().mockResolvedValue({ id: 42, uploadedById: 'owner', isPublic: false }) },
      user: { findUnique: jest.fn().mockResolvedValue({ id: 'rector', role: 'rector' }) },
      documentTemplate: { findUnique: jest.fn() },
    };
    const service = new DocumentTemplateService(prisma, {} as never, {} as never, {} as never, {} as never, new DirectoryService(prisma));
    await expect(service.updateDocumentFromTemplate(42, { isPublic: true, formData: {} }, 'rector', UserRole.RECTOR))
      .rejects.toThrow('No tienes permiso para gestionar');
    expect(prisma.documentTemplate.findUnique).not.toHaveBeenCalled();
  });

  it.each([
    [UserRole.USER, 'editor-1', undefined],
    [UserRole.RECTOR, 'rector', undefined],
    [UserRole.RECTOR, 'rector', false],
    [UserRole.USER, 'editor-1', true],
    [UserRole.ADMIN, 'admin', true],
  ])('preserves successful %s form edit (visibility %s)', async (role, actor, isPublic) => {
    const prisma: any = {
      $queryRaw: jest.fn(),
      documentWorkflow: { findFirst: jest.fn().mockResolvedValue(null) },
      document: {
        findUnique: jest.fn().mockResolvedValue({
          id: 42,
          isPublic: false,
          uploadedById: 'editor-1',
          currentVersion: 1,
          templateData: { templateId: 7 },
          versions: [{ id: 10, filename: 'document.pdf', path: '/history/document.pdf' }],
        }),
        update: jest.fn().mockResolvedValue({ id: 42 }),
      },
      user: { findUnique: jest.fn().mockResolvedValue({ id: actor, role }) },
      documentTemplate: {
        findUnique: jest.fn().mockResolvedValue({
          id: 7,
          name: 'Acta',
          isActive: true,
          fields: { fields: [] },
          outputFormat: 'pdf',
          htmlTemplate: '<p>{{title}}</p>',
          styles: '',
          pageSize: 'A4',
          orientation: 'portrait',
          documentType: { name: 'Acta' },
        }),
      },
      documentVersion: { create: jest.fn().mockResolvedValue({ id: 11 }), update: jest.fn() },
      documentAccess: { create: jest.fn() },
    };
    prisma.$transaction = jest.fn(async cb => cb(prisma));
    const documentGenerator = {
      generatePDF: jest.fn().mockResolvedValue(Buffer.from('pdf')),
      saveDocumentToFile: jest.fn(async (_buffer, filename, dir) => path.join(dir, filename)),
    };
    const thumbnailService = {
      regenerateThumbnail: jest.fn().mockResolvedValue(undefined),
    };
    const service = new DocumentTemplateService(
      prisma as never,
      documentGenerator as never,
      {} as never,
      thumbnailService as never,
      {} as never,
      new DirectoryService(prisma),
    );

    jest.spyOn(service as any, 'getInstitutionMetadata').mockResolvedValue({});
    await service.updateDocumentFromTemplate(
      42,
      { formData: { title: 'Updated' }, isPublic } as any,
      actor,
      role,
    );

    expect(prisma.documentAccess.create).toHaveBeenCalledWith({
      data: { documentId: 42, userId: actor, action: 'UPDATE' },
    });
  });

  it('creates a generic template without consulting a default document type', async () => {
    const prisma = {
      documentType: {
        findFirst: jest.fn(),
        findUnique: jest.fn(),
      },
      documentTemplate: {
        create: jest.fn().mockResolvedValue({ id: 9 }),
      },
    };
    const service = new DocumentTemplateService(
      prisma as never,
      {} as never,
      {} as never,
      {} as never,
      {} as never,
      new DirectoryService(prisma as any),
    );

    await service.create(
      {
        name: 'Plantilla nueva',
        fields: { fields: [] },
        htmlTemplate: '<p />',
      } as any,
      'creator-1',
    );

    expect(prisma.documentType.findFirst).not.toHaveBeenCalled();
    expect(prisma.documentType.findUnique).not.toHaveBeenCalled();
    expect(prisma.documentTemplate.create).toHaveBeenCalledWith(
      expect.objectContaining({
        data: expect.objectContaining({
          documentTypeId: null,
          categoryId: null,
          createdById: 'creator-1',
        }),
      }),
    );
  });

  it('validates an explicit concrete type and derives its category', async () => {
    const prisma = {
      documentType: {
        findFirst: jest.fn(),
        findUnique: jest.fn().mockResolvedValue({
          id: 8,
          isActive: true,
          categoryId: 3,
        }),
      },
      documentTemplate: {
        create: jest.fn().mockResolvedValue({ id: 9 }),
      },
    };
    const service = new DocumentTemplateService(
      prisma as never,
      {} as never,
      {} as never,
      {} as never,
      {} as never,
      new DirectoryService(prisma as any),
    );

    await service.create(
      {
        name: 'Plantilla con tipo',
        fields: { fields: [] },
        htmlTemplate: '<p />',
        documentTypeId: 8,
      } as any,
      'creator-1',
    );

    expect(prisma.documentType.findFirst).not.toHaveBeenCalled();
    expect(prisma.documentTemplate.create).toHaveBeenCalledWith(
      expect.objectContaining({
        data: expect.objectContaining({
          documentTypeId: 8,
          categoryId: 3,
        }),
      }),
    );
  });
});

describe('DocumentTemplateService.update classification boundary', () => {
  function fixture(existing: Record<string, unknown>) {
    const prisma: any = {
      documentTemplate: {
        findUnique: jest.fn().mockResolvedValue({
          id: 9,
          createdById: 'owner',
          isActive: true,
          documentTypeId: 12,
          categoryId: 99,
          ...existing,
        }),
        update: jest.fn().mockResolvedValue({ id: 9 }),
      },
      documentType: {
        findUnique: jest.fn().mockResolvedValue({
          id: 12,
          isActive: true,
          categoryId: 99,
        }),
      },
    };
    const service = new DocumentTemplateService(
      prisma as never,
      {} as never,
      {} as never,
      {} as never,
      {} as never,
      new DirectoryService(prisma as any),
    );
    return { prisma, service };
  }

  it('rejects an unknown concrete document type before persisting', async () => {
    const { prisma, service } = fixture({});
    prisma.documentType.findUnique.mockResolvedValueOnce(null);

    await expect(
      service.update(9, { documentTypeId: 404 } as any, 'owner', UserRole.ADMIN),
    ).rejects.toThrow('El tipo de documento no existe');
    expect(prisma.documentTemplate.update).not.toHaveBeenCalled();
  });

  it('rejects an inactive concrete document type before persisting', async () => {
    const { prisma, service } = fixture({});
    prisma.documentType.findUnique.mockResolvedValueOnce({
      id: 12,
      isActive: false,
      categoryId: 99,
    });

    await expect(
      service.update(9, { documentTypeId: 12 } as any, 'owner', UserRole.ADMIN),
    ).rejects.toThrow('El tipo de documento está inactivo');
    expect(prisma.documentTemplate.update).not.toHaveBeenCalled();
  });

  it('rejects a category that does not match the selected document type', async () => {
    const { prisma, service } = fixture({});

    await expect(
      service.update(
        9,
        { documentTypeId: 12, categoryId: 404 } as any,
        'owner',
        UserRole.ADMIN,
      ),
    ).rejects.toThrow(
      'La categoría indicada no corresponde al tipo de documento seleccionado',
    );
    expect(prisma.documentTemplate.update).not.toHaveBeenCalled();
  });

  it('derives the category from the selected concrete document type', async () => {
    const { prisma, service } = fixture({});

    await service.update(
      9,
      { documentTypeId: 12 } as any,
      'owner',
      UserRole.ADMIN,
    );

    expect(prisma.documentType.findUnique).toHaveBeenCalledWith({
      where: { id: 12 },
      select: { id: true, isActive: true, categoryId: true },
    });
    expect(prisma.documentTemplate.update).toHaveBeenCalledWith(
      expect.objectContaining({
        data: expect.objectContaining({ documentTypeId: 12, categoryId: 99 }),
      }),
    );
  });

  it('clears an existing type to generic on explicit null without changing category', async () => {
    const { prisma, service } = fixture({});

    await service.update(
      9,
      { documentTypeId: null } as any,
      'owner',
      UserRole.ADMIN,
    );

    const data = (prisma.documentTemplate.update as jest.Mock).mock.calls[0][0]
      .data;
    expect(data.documentTypeId).toBeNull();
    expect(data).not.toHaveProperty('categoryId');
    expect(prisma.documentType.findUnique).not.toHaveBeenCalled();
  });

  it('rejects a category-only change that would invalidate the existing type', async () => {
    const { prisma, service } = fixture({});

    await expect(
      service.update(9, { categoryId: 404 } as any, 'owner', UserRole.ADMIN),
    ).rejects.toThrow(
      'La categoría indicada no corresponde al tipo de documento seleccionado',
    );
    expect(prisma.documentTemplate.update).not.toHaveBeenCalled();
  });

  it('allows a category change for a generic template', async () => {
    const { prisma, service } = fixture({
      documentTypeId: null,
      categoryId: null,
    });

    await service.update(
      9,
      { categoryId: 5 } as any,
      'owner',
      UserRole.ADMIN,
    );

    expect(prisma.documentType.findUnique).not.toHaveBeenCalled();
    expect(prisma.documentTemplate.update).toHaveBeenCalledWith(
      expect.objectContaining({
        data: expect.objectContaining({ categoryId: 5 }),
      }),
    );
  });
});
